// Isolated `dsh web` lifecycle for the e2e harness.
//
// A run gets its own temp root:
//   <root>/home       → DSH_HOME (fresh profile: the user's profile is never touched)
//   <root>/workspace  → cwd of the `dsh web` process
//   <root>/documents  → Documents directory override for the first-use workspace
//   <root>/logs       → dsh.log, chrome.log, page dumps
//
// The plugin is loaded through a `--patch` overlay applied after the profile
// layer, so nothing is installed into any profile.

import { spawn } from 'node:child_process'
import { createWriteStream, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { setTimeout as sleep } from 'node:timers/promises'

export const DSH_CLI = '/Applications/DeepSeek Harness 2.app/Contents/Resources/runtime/cli/bin/dsh'

/** Timestamp suitable as a directory name, e.g. 2026-10-28T04-12-33-123Z. */
export function runTimestamp(date = new Date()) {
  return date.toISOString().replace(/[:.]/gu, '-')
}

/**
 * Environment for the child `dsh` process: the caller's context variables
 * (`DSH_HOME`, `DSH_PROFILE`, …) must not leak into an isolated run.
 * @param {string} dshHome absolute temp DSH_HOME
 */
export function isolatedEnv(dshHome) {
  /** @type {Record<string, string>} */
  const env = {}
  for (const [key, value] of Object.entries(process.env)) {
    if (value === undefined) continue
    if (key.startsWith('DSH_') || key.startsWith('ELECTRON_') || key === 'CHROME_USER_DATA_DIR') continue
    env[key] = value
  }
  env.DSH_HOME = dshHome
  return env
}

/**
 * Create the temp layout for one run.
 * @param {{base?: string, name: string}} options
 */
export function createRunRoot({ base = '/tmp/dsh-github-projects-e2e', name }) {
  const root = join(base, name)
  const home = join(root, 'home')
  const workspace = join(root, 'workspace')
  const documents = join(root, 'documents')
  const logs = join(root, 'logs')
  for (const dir of [home, workspace, documents, logs]) mkdirSync(dir, { recursive: true })
  return { root, home, workspace, documents, logs }
}

/**
 * Write the `--patch` overlay that (a) keeps the first-use workspace inside the
 * temp root and (b) mounts the plugin row from an absolute file path.
 * @param {{root: string, pluginEntry: string, documentsDirectory: string}} options
 */
export function writeOverlay({ root, pluginEntry, documentsDirectory }) {
  const file = join(root, 'overlay.yml')
  const yamlPath = value => `'${value.replaceAll("'", "''")}'`
  const content = [
    '# generated by scripts/e2e/run.mjs — isolated e2e overlay',
    '# 1. keep the auto-created first-use workspace inside the temp run root',
    '- id: workspace-controller',
    '  config:',
    `    documentsDirectory: ${yamlPath(documentsDirectory)}`,
    '# 2. mount the plugin host entry from its absolute path; the client bundle is',
    '#    discovered from the nearest package.json (dsh.client)',
    '- insert:',
    '    - id: github-projects',
    `      name: ${yamlPath(pluginEntry)}`,
    "      # A bare overlay row activates before the webServer service is ready;",
    "      # declaring the dependency makes the loader mount the row after it.",
    "      inject: ['webServer']",
    '',
  ].join('\n')
  writeFileSync(file, content, 'utf8')
  return file
}

/**
 * Boot `dsh web` in the run root.
 * @param {{
 *   root: string, home: string, workspace: string,
 *   overlayPath: string, logPath: string,
 *   port?: number,
 *   env?: Record<string, string>,
 * }} options
 */
export function startDshWeb({ root, home, workspace, overlayPath, logPath, port = 0, env = {} }) {
  const args = ['--profile', 'web', '--patch', overlayPath, '--no-open', '--port', String(port)]
  const log = createWriteStream(logPath, { flags: 'w' })
  const child = spawn(DSH_CLI, args, {
    cwd: workspace,
    env: { ...isolatedEnv(home), ...env },
    detached: true,
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  child.stdout.pipe(log)
  child.stderr.pipe(log)
  child.unref?.()

  let output = ''
  let exit = null
  child.stdout.on('data', (chunk) => { output += String(chunk) })
  child.stderr.on('data', (chunk) => { output += String(chunk) })
  child.on('exit', (code, signal) => { exit = { code, signal } })

  const handle = {
    child,
    root,
    logPath,
    get output() { return output },
    get exit() { return exit },
    /** Resolve the tokenized app URL that the CLI prints on startup. */
    async waitForUrl(timeoutMs = 90_000) {
      const deadline = Date.now() + timeoutMs
      while (Date.now() < deadline) {
        const match = output.match(/dsh web:\s+(http:\/\/[^\s]+)/u)
        if (match !== null) return match[1]
        if (exit !== null) {
          throw new Error(`dsh web exited before printing a URL (code ${exit.code ?? exit.signal}):\n${tail(output, 4000)}`)
        }
        await sleep(100)
      }
      throw new Error(`dsh web did not print a URL within ${timeoutMs}ms:\n${tail(output, 4000)}`)
    },
    async stop() {
      if (exit === null) {
        try { process.kill(-child.pid, 'SIGTERM') } catch { try { child.kill('SIGTERM') } catch { /* gone */ } }
        for (let i = 0; i < 50; i++) {
          if (exit !== null) break
          await sleep(100)
        }
        if (exit === null) {
          try { process.kill(-child.pid, 'SIGKILL') } catch { try { child.kill('SIGKILL') } catch { /* gone */ } }
          await sleep(200)
        }
      }
      log.end()
    },
  }
  return handle
}

/** Poll the app URL until the web server answers. */
export async function waitForHttpReady(url, { timeoutMs = 30_000 } = {}) {
  const deadline = Date.now() + timeoutMs
  let lastError = null
  while (Date.now() < deadline) {
    try {
      const response = await fetch(url, { redirect: 'manual' })
      if (response.status >= 200 && response.status < 400) return response.status
      lastError = new Error(`HTTP ${response.status}`)
    } catch (error) {
      lastError = error
    }
    await sleep(150)
  }
  throw new Error(`web server did not answer within ${timeoutMs}ms: ${lastError?.message ?? 'no response'} (${url})`)
}

export function tail(text, length = 2000) {
  const value = String(text ?? '')
  return value.length <= length ? value : `…${value.slice(-length)}`
}
